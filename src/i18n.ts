export function normalizeLanguage(value: unknown): HomepageLanguage {
  return value === "zh-CN" ? "zh-CN" : "en";
}

export function t(language: unknown, key: string, vars: Record<string, string | number> = {}): string {
  const normalized = normalizeLanguage(language);
  const source = normalized === "zh-CN" ? ZH[key as keyof typeof EN] : undefined;
  let text = source || EN[key as keyof typeof EN] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
  }
  return text;
}

export function widgetName(language: unknown, type: string, fallback = "Widget"): string {
  const key = WIDGET_KEYS[type];
  return key ? t(language, key) : fallback;
}

export function widgetTitle(language: unknown, type: string, configuredTitle: unknown, fallback = "Widget"): string {
  const title = String(configuredTitle || "").trim();
  const builtIn = BUILT_IN_TITLES[type];
  if (!builtIn) return title || fallback;
  const isBuiltIn = !title || title.toLowerCase() === builtIn.en.toLowerCase() || title === builtIn["zh-CN"];
  return isBuiltIn ? builtIn[normalizeLanguage(language)] : title;
}
